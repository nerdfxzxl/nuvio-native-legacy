import space.nuvio.nativelegacy.RecriaHdr

fun main() {
    val p = RecriaHdr
    check(p.ownsTransition(1, 1, 2, 2, true, true))
    check(!p.ownsTransition(1, 2, 2, 2, true, true))
    check(!p.ownsTransition(1, 1, 2, 3, true, true))
    check(!p.ownsTransition(1, 1, 2, 2, false, true))
    check(!p.ownsTransition(1, 1, 2, 2, true, false))
    check(p.ownsRenderedFrame(true, true, 100, 100))
    check(!p.ownsRenderedFrame(true, true, 99, 100))
    check(!p.ownsRenderedFrame(false, true, 101, 100))
    check(!p.ownsRenderedFrame(true, false, 101, 100))
    check(p.mayRecoverDetach(false, true))
    check(!p.mayRecoverDetach(true, true))
    check(!p.mayRecoverDetach(false, false))
    check(p.needsTclWorkaround("TCL", "TCL", listOf("c2.mtk.dvhe.decoder")))
    check(p.needsTclWorkaround("unknown", "tcl", listOf("OMX.MTK.VIDEO.DECODER.HEVC")))
    check(!p.needsTclWorkaround("Xiaomi", "Xiaomi", listOf("c2.mtk.hevc.decoder")))
    check(!p.needsTclWorkaround("TCL", "TCL", listOf("c2.android.hevc.decoder")))
    check(!p.needsTclWorkaround("TCL", "TCL", listOf("c2.mtk.hevc.decoder", "OMX.MS.HEVC")))
    check(!p.needsTclWorkaround("TCL", "TCL", listOf("c2.mtk.hevc.decoder", "c2.amlogic.hevc.decoder")))
    check(!p.needsTclWorkaround("", "", emptyList()))
    val normal = RecriaHdr.DetachTicket()
    check(!normal.blocksFrames())
    check(normal.send())
    check(normal.blocksFrames())
    check(!normal.send())
    check(normal.acknowledge() == RecriaHdr.DetachAction.RECREATE)
    check(normal.blocksFrames())
    normal.attaching()
    check(!normal.blocksFrames())
    check(normal.acknowledge() == RecriaHdr.DetachAction.IGNORE)
    check(!normal.expire())

    val backgroundCapture = RecriaHdr.DetachTicket()
    backgroundCapture.pause()
    check(!backgroundCapture.send())
    check(!backgroundCapture.blocksFrames())
    check(backgroundCapture.acknowledge() == RecriaHdr.DetachAction.IGNORE)

    val backgroundDetach = RecriaHdr.DetachTicket()
    check(backgroundDetach.send())
    backgroundDetach.pause()
    check(backgroundDetach.acknowledge() == RecriaHdr.DetachAction.RETAIN)
    check(backgroundDetach.blocksFrames())
    backgroundDetach.attaching()
    check(!backgroundDetach.blocksFrames())

    val timeout = RecriaHdr.DetachTicket()
    check(!timeout.expire())
    check(timeout.send())
    check(timeout.expire())
    check(!timeout.expire())
    check(timeout.acknowledge() == RecriaHdr.DetachAction.IGNORE)
    val obsolete = RecriaHdr.DetachTicket()
    check(obsolete.send())
    obsolete.cancel()
    check(!obsolete.blocksFrames())
    check(obsolete.acknowledge() == RecriaHdr.DetachAction.IGNORE)
    check(!obsolete.expire())
    val seek = RecriaHdr.StartupSeekGate()
    check(!seek.waiting())
    val firstSeek = seek.begin()
    check(seek.waiting())
    check(seek.owns(firstSeek))
    val nextSeek = seek.begin()
    check(!seek.owns(firstSeek))
    check(!seek.finish(firstSeek))
    check(seek.waiting())
    check(seek.finish(nextSeek))
    check(!seek.waiting())
    check(!seek.finish(nextSeek))
    val cancelledSeek = seek.begin()
    seek.cancel()
    check(!seek.waiting())
    check(!seek.finish(cancelledSeek))
    println("P5-C surface and startup seek handoff: PASS (55 production Kotlin assertions)")
}
