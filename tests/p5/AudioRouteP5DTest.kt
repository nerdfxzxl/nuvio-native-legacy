package space.nuvio.nativelegacy

fun main() {
    var n = 0
    fun ok(value: Boolean) { check(value) { "Q49 assertion ${n+1}" }; n++ }
    fun key(id: Int, type: Int, enc: List<Int> = listOf(2)) =
        AudioRouteP5D.Key(id, type, enc, listOf(48000), listOf(2), listOf(12))
    val arc = key(1, 10, listOf(2, 5))
    val bt = key(2, 8)
    val speaker = key(3, 2)
    ok(AudioRouteP5D.sameAudioRole(0, "English DTS-HD MA 7.1", 0, "English AC3 5.1"))
    ok(!AudioRouteP5D.sameAudioRole(0, "English", 0, "Director commentary"))
    ok(!AudioRouteP5D.sameAudioRole(0, null, 1, null))
    ok(AudioRouteP5D.fallbackSampleRate(96000, intArrayOf(48000)) == 48000)
    ok(AudioRouteP5D.fallbackSampleRate(96000, intArrayOf(96000, 48000)) == -1)
    val nativeShape = AudioRouteP5D.PcmShape(false, -1)
    val stereo48 = AudioRouteP5D.PcmShape(true, 48000)
    val restricted = AudioRouteP5D.refreshPcmShape(6, 96000, true, intArrayOf(2), intArrayOf(48000), nativeShape)
    ok(restricted == stereo48)
    ok(AudioRouteP5D.pcmShapeNeedsReselect(nativeShape, restricted, 6, 96000))
    val restored = AudioRouteP5D.refreshPcmShape(6, 96000, false, intArrayOf(2, 6), intArrayOf(48000, 96000), stereo48)
    ok(restored == nativeShape)
    ok(AudioRouteP5D.pcmShapeNeedsReselect(stereo48, restored, 2, 48000))
    ok(AudioRouteP5D.refreshPcmShape(6, 96000, false, null, null, stereo48) == stereo48)
    ok(!AudioRouteP5D.pcmShapeNeedsReselect(stereo48, stereo48, 2, 48000))
    ok(AudioRouteP5D.pcmShapeNeedsReselect(stereo48, stereo48, 6, 96000))
    val output = AudioRouteP5D.OutputPolicy(false)
    output.request(true, 0); output.request(false, 50)
    ok(!output.apply(200, false) && !output.pcm)
    output.request(true, 210); output.request(true, 230)
    ok(!output.apply(331, true) && output.apply(332, false) && output.pcm)
    output.request(false, 340)
    ok(!output.apply(450, false) && output.apply(461, false) && !output.pcm)
    ok(!AudioRouteP5D.needsStereo(6, false, intArrayOf(2, 6), false))
    ok(AudioRouteP5D.needsStereo(6, true, intArrayOf(2, 6), false))
    ok(AudioRouteP5D.needsStereo(6, false, intArrayOf(2), false))
    ok(AudioRouteP5D.needsStereo(6, false, null, true))
    val d = AudioRouteP5D.Debounce()
    d.seed(arc)
    ok(d.observe(arc, 0) == AudioRouteP5D.Debounce.Result.NONE)
    ok(d.observe(arc.copy(), 100) == AudioRouteP5D.Debounce.Result.NONE) // duplicate/volume/inventory
    ok(d.observe(bt, 200) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(d.observe(bt, 500) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(d.observe(speaker, 600) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(d.observe(speaker, 1349) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(d.observe(speaker, 1350) == AudioRouteP5D.Debounce.Result.CHANGED)
    ok(d.observe(speaker, 1500) == AudioRouteP5D.Debounce.Result.NONE)
    ok(d.observe(arc, 1600) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(d.observe(speaker, 1700) == AudioRouteP5D.Debounce.Result.NONE)
    ok(!d.pending)
    ok(d.observe(speaker.copy(rates=listOf(44100)), 1800) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(d.observe(speaker.copy(rates=listOf(44100)), 2550) == AudioRouteP5D.Debounce.Result.CHANGED)
    ok(d.observe(null, 3000) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(d.observe(null, 3750) == AudioRouteP5D.Debounce.Result.CHANGED)
    ok(d.observe(arc, 4000) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(d.observe(arc, 4750) == AudioRouteP5D.Debounce.Result.CHANGED)
    ok(d.observe(bt, 5000) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(d.observe(speaker, 9999) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(d.observe(bt, 10000) == AudioRouteP5D.Debounce.Result.UNSTABLE)
    val A = AudioRouteP5D.Action.KEEP
    ok(AudioRouteP5D.plan(true, true, true, true, false) == A)
    ok(AudioRouteP5D.plan(true, true, false, true, true) == A)
    ok(AudioRouteP5D.plan(true, true, false, false, false) == AudioRouteP5D.Action.RESELECT_PCM)
    ok(AudioRouteP5D.plan(true, false, true, false, true) == AudioRouteP5D.Action.RESELECT_ENCODED)
    ok(AudioRouteP5D.plan(false, true, false, false, true) == AudioRouteP5D.Action.ERROR)
    val hd = AudioFidelityP5A.assess("audio/true-hd", 8, 48000, 24, 0, true, true, true, false, false)
    val hdPcm = AudioFidelityP5A.assess("audio/true-hd", 8, 48000, 24, 0, true, true, false, false, false)
    ok(hd.outputFaithfulCandidate && !hdPcm.outputFaithfulCandidate)
    ok(!AudioRouteP5D.validate(true, hdPcm.outputFaithfulCandidate, true, 48000, 8, 24, 48000, 8, 16, false))
    ok(AudioRouteP5D.validate(false, false, true, 48000, 8, 24, 48000, 8, 0, true))
    ok(!AudioRouteP5D.validate(false, false, true, 48000, 8, 24, 48000, 8, 0, false))
    ok(AudioRouteP5D.validate(true, true, false, 48000, 2, 16, 48000, 2, 16, false))
    ok(!AudioRouteP5D.validate(true, true, false, 48000, 6, 16, 48000, 2, 16, false))
    ok(!AudioRouteP5D.validate(true, true, false, 48000, 2, 16, 44100, 2, 16, false))
    ok(!AudioRouteP5D.validate(true, true, false, 48000, 2, 16, 48000, 2, 8, false))
    // P8: a supported decoder may produce a compatible downgraded output
    // without changing the separate fidelity result.
    ok(hdPcm.playableCandidate && !hdPcm.outputFaithfulCandidate)
    ok(AudioRouteP5D.playableOutput(true, true, false, 48000, 2, 16, false))
    ok(AudioRouteP5D.playableOutput(true, true, false, 44100, 2, 16, false))
    ok(!AudioRouteP5D.playableOutput(true, false, false, 48000, 2, 16, false))
    ok(!AudioRouteP5D.playableOutput(true, true, false, 0, 2, 16, false))
    ok(!AudioRouteP5D.playableOutput(false, true, false, 48000, 8, 0, true))
    val center = AudioRouteP5D.stereoMix(intArrayOf(0, 0, 30000, 0, 0, 0))
    ok((center shr 16) > 0 && (center shr 16) == center.toShort().toInt())
    val rear = AudioRouteP5D.stereoMix(intArrayOf(0, 0, 0, 0, 30000, 0))
    ok((rear shr 16) > 0 && rear.toShort().toInt() == 0)
    val full = AudioRouteP5D.stereoMix(IntArray(8) { 32767 })
    ok((full shr 16) in 1..32767 && full.toShort().toInt() in 1..32767)
    val silent = AudioRouteP5D.stereoMix(IntArray(6))
    ok(silent == 0)
    val tx = AudioRouteP5D.Transaction()
    val t = tx.begin(100)
    ok(tx.owns(t) && !tx.expired(8099))
    ok(tx.expired(8100))
    ok(tx.allowReselect(t))
    ok(tx.allowReselect(t))
    ok(!tx.allowReselect(t))
    ok(tx.allowPrepare(t))
    ok(!tx.allowPrepare(t))
    tx.cancel()
    ok(!tx.owns(t) && !tx.allowPrepare(t) && !tx.allowReselect(t))
    val t2 = tx.begin(10000)
    ok(t2 != t && tx.owns(t2) && !tx.owns(t))
    ok(tx.allowReselect(t2) && !tx.allowReselect(t))
    tx.cancel()
    ok(!tx.active)
    val profiles = AudioRouteP5D.Debounce()
    profiles.seed(arc)
    val changed = arc.copy(directProfiles=listOf("AC3:48000:5.1"))
    ok(profiles.observe(changed, 0) == AudioRouteP5D.Debounce.Result.WAIT)
    ok(profiles.observe(changed, 750) == AudioRouteP5D.Debounce.Result.CHANGED)
    println("P5-D route policy: $n assertions PASS")
}
